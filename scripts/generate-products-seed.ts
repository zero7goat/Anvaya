/**
 * Writes supabase/drafts/products_seed.sql from the built-in sample catalogue,
 * so Supabase starts with exactly the products, stock and reviews the site has today.
 *
 * Run: npx tsx scripts/generate-products-seed.ts
 * Safe to re-run in the SQL editor: rows that already exist are left untouched.
 */

import { writeFileSync } from "node:fs";
import { INITIAL_SAMPLE_PRODUCTS } from "../src/services/productService";

const text = (value: string | undefined | null) => (value == null ? "null" : `'${value.replace(/'/g, "''")}'`);
const int = (value: number | undefined | null) => (value == null ? "null" : String(Math.trunc(value)));
const bool = (value: boolean) => (value ? "true" : "false");
const textArray = (values: string[] | undefined) =>
  values && values.length > 0 ? `array[${values.map(text).join(", ")}]::text[]` : "'{}'::text[]";

const products = INITIAL_SAMPLE_PRODUCTS.map(
  (p) =>
    `  (${[
      text(p.id),
      text(p.name),
      text(p.description),
      text(p.collection ?? (p.category === "Sarees" ? "ayanaa" : "alankritha")),
      text(p.category),
      text(p.subcategory),
      int(p.price),
      int(p.salePrice),
      text(p.image),
      textArray(p.additionalImages),
      bool(p.isFeatured),
      bool(p.isNewArrival),
      text(p.status),
      p.createdAt ? `${text(p.createdAt)}::timestamptz` : "now()",
      p.updatedAt ? `${text(p.updatedAt)}::timestamptz` : "now()",
    ].join(", ")})`
);

const stock = INITIAL_SAMPLE_PRODUCTS.flatMap((p) =>
  Object.entries(p.sizeStock).map(([size, quantity]) => `  (${text(p.id)}, ${text(size)}, ${int(Math.max(0, quantity))})`)
);

const reviews = INITIAL_SAMPLE_PRODUCTS.flatMap((p) =>
  p.reviews.map(
    (r) =>
      `  (${[text(r.id), text(p.id), text(r.author), int(r.rating), text(r.comment), `${text(r.date)}::date`, bool(r.verified), text(r.brandReply)].join(", ")})`
  )
);

const sql = `-- ANVAYA products seed: DRAFT FOR REVIEW. NOT APPLIED.
-- Generated by scripts/generate-products-seed.ts from the built-in sample catalogue
-- (${products.length} products, ${stock.length} stock rows, ${reviews.length} reviews).
-- Run after products_schema.sql. Existing rows are left untouched.

begin;

insert into public.products
  (id, name, description, collection, category, subcategory, price, sale_price, image,
   additional_images, is_featured, is_new_arrival, status, created_at, updated_at)
values
${products.join(",\n")}
on conflict (id) do nothing;

insert into public.product_stock (product_id, size, quantity)
values
${stock.join(",\n")}
on conflict (product_id, size) do nothing;
${
  reviews.length > 0
    ? `
insert into public.product_reviews (id, product_id, author, rating, comment, review_date, verified, brand_reply)
values
${reviews.join(",\n")}
on conflict (id) do nothing;
`
    : ""
}
commit;
`;

const out = new URL("../supabase/drafts/products_seed.sql", import.meta.url);
writeFileSync(out, sql);
console.log(`Wrote ${products.length} products, ${stock.length} stock rows and ${reviews.length} reviews to supabase/drafts/products_seed.sql`);
